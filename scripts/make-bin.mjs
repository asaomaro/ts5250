// bin/ に `ts5250` / `ts5250ctl`（POSIX シェル）と `ts5250.bat` / `ts5250ctl.bat`（Windows）の起動ファイルを作る。
//
// 目的: PATH に bin/ を足すだけで、どこからでも `ts5250` と `ts5250ctl` を打てるようにする（npm link を使わない）。
// 起動ファイルは自分の場所からリポジトリを辿るので、リポジトリを動かしても作り直しは要らない。
// **カレントディレクトリは呼び出し元のまま**にする——`ts5250` は cwd の `.env` と `profiles.local.json` を拾うため。
// 実体は `packages/cli/dist/*.js`（`npm run build` で作る）。無ければ、起動ファイルがビルドを促して終わる。
//
// 使い方: node scripts/make-bin.mjs
import { mkdirSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bin = join(root, "bin");
mkdirSync(bin, { recursive: true });

const NAMES = ["ts5250", "ts5250ctl"];

const sh = (name) => `#!/usr/bin/env sh
# 自動生成（scripts/make-bin.mjs）。手で直さない
here="$(cd "$(dirname "$0")" && pwd)"
entry="$here/../packages/cli/dist/${name}.js"
if [ ! -f "$entry" ]; then
  echo "ビルドされていません。リポジトリで npm run build を実行してください: $entry" >&2
  exit 1
fi
exec node "$entry" "$@"
`;

const bat = (name) =>
  [
    "@echo off",
    "rem generated by scripts/make-bin.mjs - do not edit",
    `set "ENTRY=%~dp0..\\packages\\cli\\dist\\${name}.js"`,
    'if not exist "%ENTRY%" (',
    "  echo Not built. Run npm run build in the repository: %ENTRY% 1>&2",
    "  exit /b 1",
    ")",
    'node "%ENTRY%" %*',
    "exit /b %ERRORLEVEL%",
    ""
  ].join("\r\n");

for (const name of NAMES) {
  const p = join(bin, name);
  writeFileSync(p, sh(name));
  chmodSync(p, 0o755);
  writeFileSync(join(bin, `${name}.bat`), bat(name));
  process.stderr.write(`作成: bin/${name}  bin/${name}.bat\n`);
}
process.stderr.write(`PATH に ${bin} を足すと、どこからでも ts5250 / ts5250ctl を打てます\n`);
