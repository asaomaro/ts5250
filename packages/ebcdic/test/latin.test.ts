describe("latinChar（CCSID 939 の SBCS 部＝CP1027）", () => {
  it("全 256 バイトが実表と同一のコードポイントを返す", () => {
    const actual = Array.from({ length: 256 }, (_, b) => latinChar(b).codePointAt(0));
    expect(actual).toEqual([...EXPECTED]);
  });

  it("期待値表そのものが 256 件ある（採取漏れの検出）", () => {
    expect(EXPECTED).toHaveLength(256);
  });

  it("常に 1 文字を返す（サロゲートペアにならない）", () => {
    for (let b = 0; b < 256; b++) expect(latinChar(b)).toHaveLength(1);
  });
});

/**
 * **2 表が互いの鏡像であることの実証＝この関数が要る理由。**
 *
 * カタカナと英小文字は 930（CP290）と 939（CP1027）で位置が入れ替わっている。
 * 930 の表しか持たないと、ホストが 930 のセッションでは「セッションのコーデックと
 * 同じ表で読み直す」ことになり、切替が無反応になる（利用者報告で判明した不具合）。
 */
describe("表示コード切替は 2 表の往復", () => {
  it("英小文字位置とカタカナ位置が 2 表で入れ替わっている", () => {
    // 930 で英小文字が居る位置は、939 ではカタカナ
    expect(katakanaChar(0x62)).toBe("a");
    expect(latinChar(0x62)).toBe("ｲ");
    // 939 で英小文字が居る位置は、930 ではカタカナ
    expect(latinChar(0x81)).toBe("a");
    expect(katakanaChar(0x81)).toBe("ｱ");
    expect(latinChar(0x91)).toBe("j");
    expect(katakanaChar(0x91)).toBe("ﾀ");
  });

  it("英数字・記号など共通の位置は 2 表で一致する（切替で動かない）", () => {
    for (const b of [0x40, 0x4b, 0x5a, 0x60, 0x6b, 0x7e, 0xc1, 0xd1, 0xe2, 0xf0, 0xf9]) {
      expect(latinChar(b)).toBe(katakanaChar(b));
    }
  });

  it("2 表が同一ではない（片方だけで切替を作れない）", () => {
    const same = Array.from({ length: 256 }, (_, b) => latinChar(b) === katakanaChar(b));
    expect(same.filter((x) => !x).length).toBeGreaterThan(0);
  });
});
