describe("katakanaChar（CCSID 930 の SBCS 部）", () => {
  it("全 256 バイトが分割前と同一のコードポイントを返す", () => {
    const actual = Array.from({ length: 256 }, (_, b) => katakanaChar(b).codePointAt(0));
    expect(actual).toEqual([...EXPECTED]);
  });

  it("期待値表そのものが 256 件ある（採取漏れの検出）", () => {
    expect(EXPECTED).toHaveLength(256);
  });

  it("常に 1 文字を返す（サロゲートペアにならない）", () => {
    for (let b = 0; b < 256; b++) expect(katakanaChar(b)).toHaveLength(1);
  });

  it("英小文字位置がカタカナに化ける（この関数の存在理由）", () => {
    // 0x81..0x89 は CCSID 37 では 'a'..'i'、930 の SBCS 部では半角カナ
    expect(katakanaChar(0x81)).not.toBe("a");
    expect(katakanaChar(0x40)).toBe(" ");
  });
});
