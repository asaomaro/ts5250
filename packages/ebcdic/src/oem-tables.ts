/** CCSID → 上位 128 の表。ここに無い CCSID はこの経路では扱わない */
export const OEM_TABLES: ReadonlyMap<number, readonly number[]> = new Map([
  [850, CP850_HIGH],
  [437, CP437_HIGH]
]);

/**
 * 上位 128 の表からバイト列を復号する。
 *
 * **どのバイトも必ず何かに対応する**（未定義位置が無い）ので、EBCDIC と同じく
 * 「読めない」を検出できない。選択が違えば化けた文字列がそのまま返る——
 * だから採用した CCSID を UI に見せて選び直せるようにしている。
 */
export function decodeOem(high: readonly number[], bytes: Uint8Array): string {
  let out = "";
  for (const b of bytes) out += String.fromCharCode(b < 0x80 ? b : high[b - 0x80]!);
  return out;
}

/** Unicode → バイトの逆引き表。初回だけ作って使い回す */
const reverse = new Map<readonly number[], Map<number, number>>();

export function reverseOem(high: readonly number[]): Map<number, number> {
  const cached = reverse.get(high);
  if (cached) return cached;
  const table = new Map<number, number>();
  for (let b = 0; b < 0x80; b++) table.set(b, b);
  // **最初に現れたバイトを採る**（同じ文字が 2 か所に出る表があるため）
  high.forEach((cp, i) => {
    if (!table.has(cp)) table.set(cp, 0x80 + i);
  });
  reverse.set(high, table);
  return table;
}
